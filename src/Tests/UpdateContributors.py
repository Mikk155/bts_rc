'''
### **Purpose:**

Checks the ``docs/assets/credits.json`` file and update as needed.

The names will be sorted alphabetically and ``AUTHORS.md`` will be updated as well as contributors in the web site.
'''

import json;
from pathlib import Path;

from Tests.PyTest import PyTest;

class UpdateContributors( PyTest ):

    m_AuthorsPath: Path = Path( PyTest.GetWorkspace(), "AUTHORS.md" );
    m_CreditsPath: Path = Path( PyTest.GetWorkspace(), "docs", "assets", "credits.json" );
    m_AuthorsContent: str = None;
    m_CreditsContent: str = None;

    def ShouldBuild( self ) -> bool:

        if self.Type == PyTest.BuildType.Release:
            return False;

        creditsList: list[str];

        with open( self.m_CreditsPath, "r" ) as fStream:
            creditsList = json.load( fStream );

        # Format object to ( ( name.lower(), index ), ... )
        creditsMap: list[tuple[str, int]] = [ ( user.lower() if isinstance( user, str ) else user[0].lower(), i ) for i, user in enumerate( creditsList ) ];

        creditsSorted: list[tuple[str, int]] = sorted( set( creditsMap ) );

        # Sortarray credits using the indexes ordering in the sorted tuple
        creditsFixed = [ creditsList[ index[1] ] for index in creditsSorted ];

        if creditsList != creditsFixed:
            self.m_CreditsContent = json.dumps( creditsFixed, indent=4 ) + "\n";

        # Apply url markdown
        for i, contributor in enumerate(creditsFixed):
            if isinstance( contributor, list ):
                creditsFixed[i] = f"[{contributor[0]}]({contributor[1]})";

        self.m_AuthorsContent: str = """<!--
This file is auto generated by src/Tests/UpdateContributors.py
To modify anyone from the ## contributors section visit docs/assets/credits.json
-->

# Project Maintainers

| RaptorSKA | Level design | [@RaptorSKA](https://github.com/RaptorSKA) |
|---|---|---|
| Mikk | Scripting | [@Mikk155](https://github.com/Mikk155) |

## Contributors
{}""".format( "".join( f"- {contributor}\n" for contributor in creditsFixed ) );

        with open( self.m_AuthorsPath, "r" ) as fStream:
            if self.m_AuthorsContent == fStream.read():
                self.m_AuthorsContent = None;

        return ( self.m_AuthorsContent is not None or self.m_CreditsContent is not None );

    def Build( self ) -> bool:

        if self.Type == PyTest.BuildType.Check:
            self.Log( "docs/assets/credits.json were modified but never commited checks!" );
            return False;

        if self.m_AuthorsContent:
            with open( self.m_AuthorsPath, "w" ) as fStream:
                fStream.write( self.m_AuthorsContent );
            self.Log( "Updated {}", self.m_AuthorsPath.relative_to( self.Workspace ) );

        if self.m_CreditsContent:
            with open( self.m_CreditsPath, "w" ) as fStream:
                fStream.write( self.m_CreditsContent );
            self.Log( "Updated and sorted {}", self.m_CreditsPath.relative_to( self.Workspace ).as_posix() );

        return True;

UpdateContributors();
